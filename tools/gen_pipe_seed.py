NUMBERED = ["5", "10", "20", "30", "40", "60", "80", "100", "120", "140", "160"]


def validate():
    prev_od = 0.0
    npses = set()
    for nps, sort, dn, od, walls in CARBON:
        assert nps not in npses, f"duplicate size {nps}"
        npses.add(nps)
        assert od > prev_od, f"OD not increasing at {nps}"
        prev_od = od
        if sort >= 14:
            assert od == sort, f"NPS>=14 must have OD==NPS at {nps}"
        for d, w in walls.items():
            assert 0 < w < od / 2, f"wall out of range {nps} {d}"
        if sort <= 10 and "STD" in walls and "40" in walls:
            assert walls["STD"] == walls["40"], f"STD!=40 at {nps}"
        if sort <= 8 and "XS" in walls and "80" in walls:
            assert walls["XS"] == walls["80"], f"XS!=80 at {nps}"
        seq = [walls[d] for d in NUMBERED if d in walls]
        assert seq == sorted(seq), f"schedule walls not monotonic at {nps}: {seq}"
    for nps, walls in STAINLESS.items():
        assert nps in npses, f"stainless size {nps} not in carbon list"
        for d, w in walls.items():
            assert d.endswith("S"), f"bad stainless designation {d}"
            assert 0 < w, f"bad stainless wall {nps} {d}"


def main():
    validate()
    sizes = []
    total = 0
    for nps, sort, dn, od, walls in CARBON:
        entries = [{"s": d, "w": w, "std": "ASME B36.10M"} for d, w in walls.items()]
        for d, w in STAINLESS.get(nps, {}).items():
            entries.append({"s": d, "w": w, "std": "ASME B36.19M"})
        total += len(entries)
        sizes.append({"nps": nps, "sort": sort, "dn": dn, "od": od, "entries": entries})
    doc = {"version": 2, "sizes": sizes}
    out = pathlib.Path(__file__).resolve().parent.parent / "PipingDatabase" / "Resources" / "PipeSeed.json"
    out.write_text(json.dumps(doc, indent=1) + "\n")
    print(f"wrote {out.name}: {len(sizes)} sizes, {total} entries")


if __name__ == "__main__":
    main()
